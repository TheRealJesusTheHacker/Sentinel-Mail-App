package net.sentinelsafeguard.mailapp

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import java.security.MessageDigest

/**
 * Icon pins, in two halves with two different authorities:
 *
 * IN-APP LOGO — the standing LOGO RULE (owner order 2026-11-08:
 * "You use my logo not your invention"). Every in-app company
 * surface (sign-in, lock, About) renders the owner's real logo
 * (your_files/brand/sentinel-safeguard-logo.jpg, the full lockup),
 * and [inAppLogoIsTheSourceFileItself] pins that file byte-for-byte.
 * That rule is untouched.
 *
 * LAUNCHER + NOTIFICATION MARKS — owner-approved exception
 * (2026-11-10): Skyler asked for a Sentinel Mail icon "different
 * from the actual logo — similar not same," reviewed three
 * concepts, and picked concept A: the Sentinel triangle outline
 * with the envelope flap folded into its geometry, emerald on
 * #060806. The approved artwork is preserved in the repo at
 * brand/sentinel-mail-icon-master.png, and every launcher PNG
 * plus the notification silhouette is a MECHANICAL derivation of
 * it (resize / uniform inset / brightness-to-alpha — no redraw),
 * generated by tools/generate_mail_icon.py. These tests pin the
 * derived bytes so the shipped mark can never silently drift
 * from the approved one, and pin that no drawn vector foreground
 * exists.
 */
class LauncherIconTest {

    private fun resDir(): File {
        val candidates = listOf(
            File("src/main/res"),
            File("app/src/main/res"),
        )
        return candidates.firstOrNull { File(it, "values/colors.xml").isFile }
            ?: throw AssertionError("res dir not found from ${File("").absolutePath}")
    }

    private fun sha256(f: File): String {
        val digest = MessageDigest.getInstance("SHA-256")
        f.inputStream().use { input ->
            val buf = ByteArray(8192)
            while (true) {
                val n = input.read(buf)
                if (n < 0) break
                digest.update(buf, 0, n)
            }
        }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }

    @Test
    fun noDrawnVectorForegroundExists() {
        assertFalse(
            "a drawn vector mark must never ship",
            File(resDir(), "drawable/ic_launcher_foreground.xml").exists(),
        )
    }

    @Test
    fun adaptiveIconResolvesToRasterMailMarkForeground() {
        val xml = File(resDir(), "mipmap-anydpi-v26/ic_launcher.xml").readText()
        assertTrue(xml.contains("@mipmap/ic_launcher_foreground"))
        assertFalse(xml.contains("@drawable/ic_launcher_foreground"))
        assertTrue(xml.contains("@color/ic_launcher_background"))
    }

    @Test
    fun launcherPngsMatchOwnerApprovedMailMarkBytes() {
        // Concept A, owner-approved 2026-11-10; derivations of
        // brand/sentinel-mail-icon-master.png (see class header).
        val expected = mapOf(
            "mipmap-mdpi/ic_launcher.png" to
                "0162f59b11a5e55c7e424ca4246a3d3e4a168e463831b804dc348197684ccc65",
            "mipmap-mdpi/ic_launcher_foreground.png" to
                "0eb787443864f5a5de08408372d9db319ddae65b3cb3c5b4035228ee33809888",
            "mipmap-hdpi/ic_launcher.png" to
                "8c02747840ed877931806eebd71d2de264b6fc7e67e2e605669e9ffbfca7c450",
            "mipmap-hdpi/ic_launcher_foreground.png" to
                "3358d168b66e12bcdcd81f6ca4eb302d460542c05f3a246315dbc62b40867589",
            "mipmap-xhdpi/ic_launcher.png" to
                "182430e4a77592cbcc48b21a10cdfb5a3d667cf9a4f4bda66aa79696897a0e10",
            "mipmap-xhdpi/ic_launcher_foreground.png" to
                "f7d863d574b947c96173c90dacc5350c6c9d3d4608d183097a70e7bc65c877e3",
            "mipmap-xxhdpi/ic_launcher.png" to
                "ac8ac4d81b17c5613a489d1e885962a899f33b57c2272747bc0ed92b87d17a14",
            "mipmap-xxhdpi/ic_launcher_foreground.png" to
                "acd8d701992a3c58d41f9efae417e356bc45f8c5e047498c4fe56bd7ab70dc52",
            "mipmap-xxxhdpi/ic_launcher.png" to
                "143c5bfdc3bfb54dcddf4670e8e86ec958dc0efec4bb97ad5b4e30334a4687f0",
            "mipmap-xxxhdpi/ic_launcher_foreground.png" to
                "128b3ef78e7867e5598fe47778e90163ea197ec841085192e0512c8d2726b45e",
        )
        for ((path, hash) in expected) {
            val f = File(resDir(), path)
            assertTrue("$path must exist", f.isFile)
            assertEquals("$path must stay byte-identical to the approved Mail mark package", hash, sha256(f))
        }
    }

    @Test
    fun inAppLogoIsTheSourceFileItself() {
        val logo = File(resDir(), "drawable-nodpi/sentinel_logo.jpg")
        assertTrue(logo.isFile)
        assertEquals(
            "8d373bf2755f1b9f80d6d9498d7b08924501d368e854635e7091639fa8821910",
            sha256(logo),
        )
    }

    @Test
    fun notificationSilhouetteStaysTheDerivedMailMark() {
        // The full concept-A mark (triangle + flap V), mechanically
        // derived from the approved master by brightness-to-alpha;
        // verified legible at 24dp before pinning.
        val icon = File(resDir(), "drawable-nodpi/ic_stat_sentinel.png")
        assertTrue(icon.isFile)
        assertEquals(
            "1940bb979b58cdf0a7fd441406dc174a594727e57eef474acf6f903f935ae88b",
            sha256(icon),
        )
    }
}
